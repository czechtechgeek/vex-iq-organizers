#!/usr/bin/env python3
"""
models.py — manifest of built models: validate it, generate MODELS.md and JSON.

Usage:
    python3 tools/models.py validate      # check the manifest against the filesystem and the catalog
    python3 tools/models.py md            # write MODELS.md (generated, do not edit by hand)
    python3 tools/models.py md --check    # exit 1 when MODELS.md is stale (used by CI)
    python3 tools/models.py json          # machine-readable dump
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import yaml

BASE = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE / "tools"))

import catalog  # noqa: E402

MANIFEST = BASE / "catalog" / "models.yaml"
OUT_MD = BASE / "MODELS.md"

KINDS = {"gridfinity_tray", "case_insert", "baseplate", "accessory", "holder"}
STATUSES = {"draft", "verified", "printed"}
STATUS_ICON = {"draft": "draft", "verified": "verified", "printed": "printed"}


def models() -> list[dict]:
    if not MANIFEST.exists():
        raise SystemExit(f"missing {MANIFEST}")
    return yaml.safe_load(MANIFEST.read_text(encoding="utf-8")) or []


def expected_footprint(kind: str | None, cells: int | None) -> float | None:
    """Expected outer size for one axis, or None when the grid does not apply.

    Gridfinity baseplates are 42n; bins and trays are 42n - 0.5 (0.25 mm per side).
    Case-fitted inserts follow the case interior, so they cannot be checked here.
    """
    if not isinstance(cells, int):
        return None
    if kind == "baseplate":
        return cells * 42.0
    if kind in ("gridfinity_tray", "accessory"):
        return cells * 42.0 - 0.5
    return None


def validate() -> list[str]:
    errs: list[str] = []
    known_parts = {p["id"] for p in catalog.parts()}
    ids = set()
    for m in models():
        mid = m.get("id")
        if not mid:
            errs.append(f"model without id: {m}")
            continue
        if mid in ids:
            errs.append(f"duplicate model id: {mid}")
        ids.add(mid)
        if m.get("kind") not in KINDS:
            errs.append(f"{mid}: unknown kind {m.get('kind')!r}")
        if m.get("status") not in STATUSES:
            errs.append(f"{mid}: unknown status {m.get('status')!r}")
        scad = m.get("scad")
        if scad and not (BASE / scad).exists():
            errs.append(f"{mid}: scad file not found: {scad}")
        preview = m.get("preview")
        if preview and not (BASE / preview).exists():
            errs.append(f"{mid}: preview image not found: {preview}")
        cells = m.get("cells") or {}
        if not isinstance(cells.get("x"), int) or not isinstance(cells.get("y"), int):
            errs.append(f"{mid}: cells.x/y must be integers")
        size = m.get("size_mm") or {}
        # cross-check the footprint against the grid spec:
        #   baseplates are 42n, bins/trays are 42n - 0.5; case inserts follow the case
        for axis in ("x", "y"):
            want = expected_footprint(m.get("kind"), cells.get(axis))
            if want is not None and size.get(axis) and abs(size[axis] - want) > 0.05:
                errs.append(f"{mid}: size_mm.{axis}={size[axis]} does not match "
                            f"{cells[axis]} cells ({want})")
        if m.get("height_u") and size.get("z"):
            want = m["height_u"] * 7
            if abs(size["z"] - want) > 0.05:
                errs.append(f"{mid}: size_mm.z={size['z']} does not match {m['height_u']}U ({want})")
        for part_id in (m.get("parts_covered") or {}):
            if part_id not in known_parts:
                errs.append(f"{mid}: parts_covered references unknown part {part_id!r}")
        for pocket in (m.get("pockets") or []):
            for part_id in (pocket.get("parts") or []):
                if part_id not in known_parts:
                    errs.append(f"{mid}: pocket references unknown part {part_id!r}")
    return errs


def counts() -> dict[str, int]:
    out = {s: 0 for s in STATUSES}
    printed = 0
    for m in models():
        out[m["status"]] = out.get(m["status"], 0) + 1
        printed += int(m.get("prints") or 0)
    out["total"] = len(models())
    out["prints_total"] = printed
    return out


def render_md() -> str:
    ms = models()
    c = counts()
    lines = [
        "# Models catalog",
        "",
        "Generated by `tools/models.py` from `catalog/models.yaml` — **do not edit by hand**.",
        "",
        f"**{c['total']} models** · {c['verified']} verified · {c['printed']} printed · "
        f"{c['draft']} draft · {c['prints_total']} physical prints so far",
        "",
        "| model | kind | cells | height | size (mm) | weight | status | prints | file |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for m in ms:
        cells = m.get("cells") or {}
        size = m.get("size_mm") or {}
        size_txt = " x ".join(
            f"{size[k]:g}" if isinstance(size.get(k), (int, float)) else "?"
            for k in ("x", "y", "z")
        )
        scad = m.get("scad")
        file_txt = f"[{pathlib.Path(scad).name}]({scad})" if scad else "-"
        height_txt = f"{m['height_u']}U" if m.get("height_u") else "-"
        weight_txt = f"{m['weight_g']} g" if m.get("weight_g") else "-"
        lines.append(
            f"| **{m['name']}** | {m['kind']} | {cells.get('x')}x{cells.get('y')} | "
            f"{height_txt} | {size_txt} | {weight_txt} | {m['status']} | "
            f"{m.get('prints') or 0} | {file_txt} |"
        )
    lines.append("")
    for m in ms:
        lines.append(f"## {m['name']}")
        lines.append("")
        if m.get("preview"):
            lines.append(f"![{m['name']}]({m['preview']})")
            lines.append("")
        lines.append(f"- **id:** `{m['id']}` · **kind:** {m['kind']} · **status:** {m['status']}"
                     f" · **prints:** {m.get('prints') or 0}")
        covered = m.get("parts_covered") or {}
        if covered:
            parts_txt = ", ".join(f"`{k}` x{v}" for k, v in sorted(covered.items()))
            lines.append(f"- **parts covered:** {parts_txt}")
        for pocket in (m.get("pockets") or []):
            parts_txt = ", ".join(f"`{p}`" for p in (pocket.get("parts") or [])) or "-"
            lines.append(f"- **pocket:** {pocket.get('type')} x{pocket.get('count')} → {parts_txt}")
        if m.get("scad"):
            lines.append(f"- **source:** [`{m['scad']}`]({m['scad']})")
        if m.get("note"):
            lines.append(f"- {m['note']}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["validate", "md", "json"])
    ap.add_argument("--check", action="store_true", help="with 'md': fail when the file is stale")
    a = ap.parse_args()

    if a.cmd == "validate":
        errs = validate()
        if errs:
            print("model manifest errors:")
            for e in errs:
                print("  x", e)
            return 1
        c = counts()
        print(f"OK: {c['total']} models ({c['verified']} verified, {c['draft']} draft, "
              f"{c['prints_total']} prints)")
        return 0
    if a.cmd == "json":
        print(json.dumps({"models": models(), "counts": counts()},
                         ensure_ascii=False, indent=1))
        return 0
    if a.cmd == "md":
        text = render_md()
        if a.check:
            current = OUT_MD.read_text(encoding="utf-8") if OUT_MD.exists() else ""
            if current != text:
                print("MODELS.md is stale — run: python3 tools/models.py md")
                return 1
            print("MODELS.md is up to date")
            return 0
        OUT_MD.write_text(text, encoding="utf-8")
        print(f"wrote {OUT_MD.relative_to(BASE)} ({len(models())} models)")
        return 0
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
